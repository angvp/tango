#!/bin/sh
# Runs what CI runs (.github/workflows/ci.yml): gofmt, vet, build, the tests,
# the build-artifact guard and the offline Markdown link check. The guard
# (scripts/check-artifacts.sh) looks at your change against GUARD_BASE, or
# HEAD~1 and the working tree when that is not set. Tests use SQLite unless TANGO_TEST_DSN
# names a PostgreSQL or MySQL database; the link check runs lychee, or the pinned lychee
# Docker image, and is skipped, loudly, when neither is available.
set -eu
cd "$(dirname "$0")/.."

scripts/check-artifacts.sh
test -z "$(gofmt -l .)" || { gofmt -l .; echo "gofmt: format these files" >&2; exit 1; }
# The admin stylesheet is generated by the Tailwind CSS v3.4.19 standalone CLI.
# The check runs when TAILWIND_CLI names that binary, and is skipped loudly
# otherwise, as the link check is.
if [ -n "${TAILWIND_CLI:-}" ]; then
	scripts/admin-css.sh "$TAILWIND_CLI" --check
else
	echo "SKIPPED: admin stylesheet freshness (set TAILWIND_CLI to the Tailwind CSS v3.4.19 CLI)" >&2
fi
go vet ./...
go build ./...
# ./... on SQLite; only the dialect-sensitive packages when TANGO_TEST_DSN names
# PostgreSQL or MySQL (see scripts/dialect-manifest.txt).
packages=$(scripts/dialect-packages.sh) || exit 1
go test -count=1 $packages
# The room goroutine is the single owner of the realtime sequence counter; -race
# is what keeps that ownership checked. Needs cgo.
go test -race -count=1 ./realtime/...

# These are their own Go modules, so ./... above skips
# them. The cache adapters' conformance tests need a server and skip without
# TANGO_TEST_REDIS_URL / TANGO_TEST_MEMCACHE_ADDR.
for module in storage/s3 storage/gcs cache/redis cache/memcache; do
	(cd "$module" && ! gofmt -l . | grep . && go vet ./... && go test -count=1 ./...)
done

if command -v lychee >/dev/null 2>&1; then
	lychee --offline --include-fragments --no-progress './**/*.md'
elif docker info >/dev/null 2>&1; then
	docker run --rm -v "$PWD":/input:ro -w /input lycheeverse/lychee:0.24.2 --offline --include-fragments --no-progress './**/*.md'
else
	echo "SKIPPED: Markdown links (install lychee: brew install lychee, or start Docker)" >&2
fi
