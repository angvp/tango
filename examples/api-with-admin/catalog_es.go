import "github.com/angvp/tango/i18n"

// registerCatalogs adds the example's Spanish. The admin ships English only;
// a host that wants another language supplies the catalog, here "es" for
// every key the admin uses and a small "es-MX" that overrides three of them
// (a request for es-MX gets the es text for every other key).
func registerCatalogs() {
	i18n.RegisterCatalog("es", spanish)
	i18n.RegisterCatalog("es-MX", spanishMexico)
}

